vim.opt.rtp:prepend(vim.fn.getcwd())
local review = require("diffreview")
local git = require("diffreview.git")
local root = vim.fn.tempname()
vim.fn.mkdir(root, "p")
local function run(args)
	return git.run(root, args)
end
local function write(path, lines)
	local file = assert(io.open(root .. "/" .. path, "wb"))
	assert(file:write(table.concat(lines, "\n") .. "\n"))
	file:close()
end
local function equal(a, b)
	assert(vim.deep_equal(a, b), vim.inspect(a) .. " != " .. vim.inspect(b))
end
run({ "init", "-b", "test" })
run({ "config", "user.name", "Test" })
run({ "config", "user.email", "test@example.invalid" })
write("a file.lua", { "return 1" })
write("b.lua", { "return 2" })
write("deleted.lua", { "return 3" })
run({ "add", "." })
run({ "commit", "-m", "base" })
run({ "branch", "base" })
write("a file.lua", { "return 10" })
write("b.lua", { "return 20" })
assert(vim.uv.fs_unlink(root .. "/deleted.lua"))
vim.cmd.cd(root)
review.setup({ state_dir = root .. "/state", auto_refresh = false, show_reviewed = false })
equal(review.active(), false)
review.open("base")
local s = review.state()
equal(review.active(), true)
vim.cmd.tabprevious()
equal(review.active(), false)
vim.cmd.tabnext()
equal(#s.entries, 3)
equal(vim.api.nvim_buf_get_lines(s.entries[1].left_buf, 0, -1, false), { "return 1" })
equal(vim.bo[s.entries[1].left_buf].buftype, "nofile")
equal(vim.bo[s.entries[1].left_buf].filetype, "")
vim.cmd.cnext()
vim.wait(100, function()
	return s.current == s.entries[2].key
end)
equal(s.current, s.entries[2].key)
equal(vim.api.nvim_win_get_buf(s.left_win), s.entries[2].left_buf)
review.select(s.entries[1].key)
review.toggle()
equal(#vim.fn.getqflist(), 2)
equal(s.current, s.entries[2].key)
review.toggle_all()
equal(#vim.fn.getqflist(), 3)
review.toggle_all()
write("a file.lua", { "return 100" })
review.refresh()
equal(s.entries[1].done, false)
equal(#vim.fn.getqflist(), 3)
-- Do not mark stale on-disk changes as reviewed before refreshing.
write("b.lua", { "return 200" })
equal(pcall(review.toggle, s.entries[2].key), false)
review.refresh()
review.select(s.entries[3].key)
review.toggle()
review.select(s.entries[1].key)
vim.cmd.checktime()
review.toggle()
local first_key = s.entries[1].key
vim.cmd.tabclose()
review.open("base")
s = review.state()
equal(s.entries[1].done, true)
equal(s.entries[3].done, true)
equal(#vim.fn.getqflist(), 1)
-- A new file enters the inventory after Git starts tracking it.
write("new.lua", { "return 4" })
run({ "add", "new.lua" })
review.refresh()
equal(#s.entries, 4)
-- Exercise actual Snacks finder/formatter using the locally installed dependency.
local snacks = vim.env.DIFFREVIEW_SNACKS
if snacks then
	vim.opt.rtp:prepend(snacks)
	require("snacks").setup({ picker = { enabled = true }, scratch = { root = root .. "/scratch" } })
	local picker = review.pick()
	assert(
		vim.wait(3000, function()
			return #picker:items() == 2
		end),
		"Picker has no results"
	)
	for _, item in ipairs(picker:items()) do
		assert(item.file and item.key and item.text)
	end
	local picker_win = vim.api.nvim_get_current_win()
	picker.opts.actions.review_toggle(picker, picker:items()[1])
	assert(vim.wait(1000, function()
		return #picker:items() == 1
	end))
	equal(vim.api.nvim_get_current_win(), picker_win)
	picker.opts.actions.review_all(picker)
	assert(vim.wait(1000, function()
		return #picker:items() == 4
	end))
	picker:close()
	-- Review notes use actual Snacks persistence, selection metadata and toggling.
	vim.fn.writefile({ "Existing review notes" }, s.notesfile)
	local notes = review.notes()
	local notes_path = vim.api.nvim_buf_get_name(notes.buf)
	equal(vim.bo[notes.buf].filetype, "markdown")
	equal(vim.api.nvim_buf_get_lines(notes.buf, 0, -1, false), { "Existing review notes" })
	vim.api.nvim_buf_set_lines(notes.buf, 0, -1, false, { "Updated scratch notes" })
	review.notes()
	assert(vim.wait(1000, function()
		return vim.fn.bufwinid(notes.buf) == -1
	end))
	equal(vim.fn.readfile(notes_path), { "Updated scratch notes" })
	equal(vim.fn.readfile(s.notesfile), { "Existing review notes" })
	local listed = require("snacks").scratch.list()
	assert(
		vim.iter(listed):any(function(item)
			return vim.uv.fs_realpath(item.file) == vim.uv.fs_realpath(notes_path)
		end),
		vim.inspect({ listed = listed, notes_path = notes_path })
	)
	vim.cmd.cd(root .. "/state")
	notes = review.notes()
	equal(vim.api.nvim_buf_get_name(notes.buf), notes_path)
	equal(vim.api.nvim_buf_get_lines(notes.buf, 0, -1, false), { "Updated scratch notes" })
	notes:close()
	vim.cmd.cd(root)
end
-- Revision-to-revision comparisons and rename path parsing.
run({ "add", "-A", "--", "*.lua" })
run({ "commit", "-m", "changes" })
run({ "mv", "a file.lua", "renamed file.lua" })
run({ "commit", "-m", "rename" })
local renamed = git.entries(root, "HEAD~1", "HEAD")
equal(#renamed, 1)
equal(renamed[1].status, "R")
equal(renamed[1].old, "a file.lua")
equal(renamed[1].path, "renamed file.lua")
vim.cmd.tabclose()
review.open("HEAD~1", "HEAD")
s = review.state()
equal(vim.bo[s.entries[1].buf].buftype, "nofile")
review.toggle()
equal(#vim.fn.getqflist(), 0)
-- Updating either side invalidates the fingerprint, even with identical right content.
local old_fingerprint = s.entries[1].fingerprint
write("renamed file.lua", { "return 999" })
run({ "add", "renamed file.lua" })
run({ "commit", "-m", "later" })
review.refresh()
assert(s.entries[1].fingerprint ~= old_fingerprint)
equal(s.entries[1].done, false)
-- Binary bytes and symlink targets must affect review state.
write("binary.dat", { "before\0bytes" })
assert(vim.uv.fs_symlink("b.lua", root .. "/link"))
run({ "add", "binary.dat", "link" })
run({ "commit", "-m", "special files" })
write("binary.dat", { "after\0bytes" })
assert(vim.uv.fs_unlink(root .. "/link"))
assert(vim.uv.fs_symlink("new.lua", root .. "/link"))
local special = git.entries(root, "HEAD")
equal(#special, 2)
equal(special[1].binary, true)
equal(special[2].right, "new.lua")
-- Save events discover new tracked changes without manually refreshing.
vim.cmd.tabclose()
review.setup({ state_dir = root .. "/state", auto_refresh = true, show_reviewed = true })
review.open("HEAD")
s = review.state()
write("b.lua", { "return 300" })
vim.api.nvim_exec_autocmds("BufWritePost", { pattern = root .. "/b.lua" })
assert(vim.wait(3000, function()
	return #s.entries == 3
end))
-- All-files mode toggles the checkbox in place without navigating or filtering.
review.select(s.entries[1].key)
local selected, size = s.current, #vim.fn.getqflist()
local run_git, calls = git.run, 0
git.run = function(...)
	calls = calls + 1
	return run_git(...)
end
review.toggle()
equal(s.current, selected)
equal(#vim.fn.getqflist(), size)
equal(s.entries[1].done, true)
assert(vim.fn.getqflist()[1].text:match("^%[x%]"))
assert(calls <= 3, "Marking should only query the selected comparison")
review.toggle()
equal(s.entries[1].done, false)
git.run = run_git
print("DiffReview integration tests passed")
vim.cmd("qa!")
